-- B.2: backfill existing rows to family_id = 'etch-founder-1', then tighten
-- ============================================================================
-- This migration runs in a single transaction (Drizzle's migrator wraps each
-- migration file in BEGIN ... COMMIT). If any statement fails, the entire
-- migration rolls back - no partial state.
--
-- Sequence:
--   1. INSERT the founder family row (resolves ownerUserId via email lookup)
--   2. INSERT MEMBERSHIPS rows for every existing user (idempotent via ON CONFLICT)
--   3. UPDATE every health/training table to set family_id = 'etch-founder-1'
--      for any row where it's currently NULL
--   4. ALTER COLUMN family_id SET NOT NULL on every table (auto-generated by drizzle)
--
-- After this migration:
--   - Every row in every health table has a non-null family_id
--   - Every signed-in user has a MEMBERSHIPS row linking them to a family
--   - The 'etch-founder-1' family becomes the multi-tenant root for the
--     existing 7-person family deployment. Future families get UUIDs/nanoids.

-- Written for the original deployment, which had already run it before this
-- repository was published. The founder's email is replaced with a placeholder.
-- On a fresh database there are no users yet, so these inserts add nothing.
--
-- 1. Founder family. ownerUserId resolved by email so we don't have to hardcode
--    Kinde subs. If the OP's email isn't in users for any reason, this insert
--    returns 0 rows and subsequent statements will fail loudly - which is
--    what we want (better than silently shipping a broken state).
INSERT INTO "families" (id, name, owner_user_id, created_at, updated_at)
SELECT 'etch-founder-1', 'Michael''s family', id, now(), now()
FROM "users"
WHERE email = 'founder@example.com'
LIMIT 1
ON CONFLICT (id) DO NOTHING;
--> statement-breakpoint

-- 2. One MEMBERSHIPS row per existing user. OP becomes owner; everyone else
--    is a member. ON CONFLICT DO NOTHING means rerunning the migration is
--    safe (composite PK (user_id, family_id) prevents duplicates).
INSERT INTO "memberships" (user_id, family_id, role, joined_at)
SELECT
  id,
  'etch-founder-1',
  CASE WHEN email = 'founder@example.com' THEN 'owner' ELSE 'member' END,
  now()
FROM "users"
ON CONFLICT (user_id, family_id) DO NOTHING;
--> statement-breakpoint

